// 캐러셀 기획 수정 — 규칙·출력 형식은 원본 프롬프트를 그대로 싣고, 그 위에 '기존 기획안을 어떻게 고칠지'만 덧붙인다.
// 가장 흔한 지시는 후크 안 교체("B안으로")다. 이때 1컷만 바꾸면 열린 고리·감정 곡선이 어긋나므로
// 연결된 부분까지 함께 맞추게 하고, 반대로 바꿀 이유 없는 컷은 건드리지 않게 한다.
function buildCarouselRevisePrompt({ original, instruction, voice, topic, cafe, caption }) {
  const context =
    cafe && caption
      ? `[컨텍스트] 아래는 이 강의에 대해 확정된 콘텐츠다. 캐러셀은 이 내용과 메시지·표현이 일관되어야 한다.
[확정된 카페 서머리]
${cafe}

[확정된 인스타 캡션]
${caption}

`
      : '';

  return `${context}${buildCarouselPrompt({ voice, topic })}

[수정 작업 — 위 규칙과 출력 형식을 그대로 지키면서, 아래 [기존 기획안]을 [수정 지시]대로 고쳐 기획안 전체를 다시 출력한다]
▸ 후크 안을 바꾸라는 지시(예: "B안으로 다시 기획")일 때
  · [후크 후보] A안·B안·C안의 문구와 근거는 그대로 두고, '채택' 줄만 지시한 안으로 옮긴다. 후보를 새로 뽑지 않는다.
  · CUT 1을 그 안의 헤드카피로 다시 쓴다. 서브카피·본문·장면 디렉션·넘김 유도도 그 갈래의 공식에 맞게 다시 짠다
    (공감형 = 속마음 인용·장면 재현·오해 뒤집기 / 참여유도형 = 결과 먼저·과거→현재·너도 가능).
    강의 화면·강사·수업 장면 금지는 그대로다.
  · 1컷이 던지는 것이 달라졌으니 [열린 고리] 줄과 그 고리를 닫는 proof·result 컷을 함께 맞춘다.
    참여유도형이면 "그 결과물을 만들게 되는 수업"이 눈에 보이게, 공감형이면 "그 막힘이 풀린 장면"으로 닫는다.
    감정 곡선의 첫 구간과, 필요하면 핵심 메시지도 새 1컷에 맞게 고친다.
  · CUT 2(empathy)가 새 1컷 뒤에 자연스럽게 이어지는지 확인한다. 어색하면 그 컷의 서브카피·넘김 유도만 손본다.
  · 나머지 컷은 새 1컷과 충돌하지 않으면 그대로 둔다. 바꿀 이유가 없는 컷을 억지로 다시 쓰지 않는다.
  · 자막에 없는 완성작·수강생 작품·경력을 지어내서 참여유도형을 만들지 않는다. 근거가 약하면 자막에 있는
    가장 가까운 장면으로 쓰고, 그 사정을 후크 후보의 근거 줄에 한 줄 적는다.
▸ 그 외 지시(특정 컷·문구·장면·분량 수정)일 때
  · 지시한 부분만 고치고 나머지 컷은 유지한다. 컷 하나에 관한 지시면 그 컷만 달라진 게 눈에 보여야 한다.
  · 컷을 늘리거나 줄이라는 지시가 아니면 총 컷 수를 바꾸지 않는다.
▸ 어떤 지시든
  · 역할 순서·슬러그 규칙·audience/solution 본문 표기 형식·후크 후보 표기(A안/B안/C안/채택)는 유지한다.
  · [컷 수 공통 규칙]을 다시 적용한다 — ${CAROUSEL_CUT_MIN}~${CAROUSEL_CUT_MAX}컷 안에서, 개요의 총 컷 수 = 감정 곡선 마지막 번호 = 실제 CUT 개수.
    기존 기획안이 이 규칙을 어기고 있었다면(예: 개요 13컷인데 CUT 14개) 이번에 바로잡는다.
  · 자막에 없는 사실은 추가하지 않는다.
  · 수정된 기획안 전문만 출력한다(설명·머리말·"무엇을 바꿨는지" 요약 없이).

[기존 기획안]
${original}

[수정 지시]
${instruction}`;
}

